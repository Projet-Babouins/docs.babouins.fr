export type IconName = keyof typeof PATHS;

/** Crée l'élément SVG d'une icône. Les tracés sont des constantes du code : pas d'entrée utilisateur ici. */
export function icon(name: IconName, size = 16): SVGElement {
	const template = document.createElement('template');
	template.innerHTML = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${PATHS[name]}</svg>`;
	return template.content.firstElementChild as SVGElement;
}

/** Remplit les `<span data-icon="…">` écrits dans le HTML de la page. */
export function hydrateIcons(root: ParentNode = document): void {
	for (const holder of root.querySelectorAll<HTMLElement>('[data-icon]')) {
		holder.replaceChildren(icon(holder.dataset.icon as IconName, Number(holder.dataset.size) || 16));
	}
}
